"""Pack captured real-world data into source/src/data.js (realism stage 3). Run with python3 -I.

  python3 -I tools/pack-data.py <Copernicus GLO-30 N24_E039 .tif> > src/data.js

DEM: Copernicus GLO-30 (c) DLR e.V. 2010-2014 and (c) Airbus Defence and Space GmbH 2014-2018, provided under
COPERNICUS by the European Union and ESA; free and open. Adapted from Madinah Horizon's tools/pack-data.py.
"""
import sys, base64
import numpy as np
from PIL import Image

Image.MAX_IMAGE_PIXELS = None
dem = np.asarray(Image.open(sys.argv[1]), dtype=np.float32)  # 3600x3600, rows 25N -> 24N, cols 39E -> 40E


def patch(name, lat0, lat1, lon0, lon1, w, h, base, step):
    # sample on a regular lat/lon grid (row 0 = north), heights above `base` in `step` m, 8 bit
    out = np.zeros((h, w), np.uint8)
    for j in range(h):
        lat = lat1 - (lat1 - lat0) * j / (h - 1)
        for i in range(w):
            lon = lon0 + (lon1 - lon0) * i / (w - 1)
            r, c = (25 - lat) * 3600, (lon - 39) * 3600
            r0, c0 = int(r), int(c); fr, fc = r - r0, c - c0
            v = (dem[r0, c0] * (1 - fc) + dem[r0, c0 + 1] * fc) * (1 - fr) + (dem[r0 + 1, c0] * (1 - fc) + dem[r0 + 1, c0 + 1] * fc) * fr
            out[j, i] = max(0, min(255, round((v - base) / step)))
    b64 = base64.b64encode(out.tobytes()).decode()
    return f"const {name} = {{ lat0: {lat0}, lat1: {lat1}, lon0: {lon0}, lon1: {lon1}, w: {w}, h: {h}, base: {base}, step: {step}, b64: '{b64}' }};"


print('// ============================================================================')
print('// captured real-world data (realism stage 3), generated by tools/pack-data.py: do not edit by hand')
print('// ============================================================================')
print('// Elevation: Copernicus GLO-30 DEM (ESA / Airbus, free and open). The world maps it into its composed (not to')
print('// scale) geography in shaders.js: each massif\'s real summit sits where the composition puts it.')
print(patch('DEM_UHUD', 24.495, 24.55, 39.57, 39.68, 112, 56, 590, 2))
print(patch('DEM_AYR', 24.355, 24.42, 39.50, 39.62, 88, 48, 600, 2))
print(patch('DEM_SAL', 24.466, 24.489, 39.586, 39.611, 40, 36, 595, 1))

# Wadi al-Aqiq from OpenStreetMap (c) OpenStreetMap contributors, ODbL: ways 960090164 and 1235902746, fetched as
# Nominatim geometry (optional argv[2..]: the saved JSON files). Packed as the course's east-west offset from the
# mosque (x, metres east) every 100 m along z (south), in the world's composed scale AQS.
if len(sys.argv) > 2:
    import json, math
    LAT0, LON0, AQS = 24.4672, 39.6111, .5
    KX, KZ = math.cos(math.radians(LAT0)) * 111320, 110574
    pts = []
    for f in sys.argv[2:]:
        for e in json.load(open(f)):
            if e.get('osm_id') in (960090164, 1235902746):
                pts += [((lo - LON0) * KX * AQS, -(la - LAT0) * KZ * AQS) for lo, la in e['geojson']['coordinates']]
    pts.sort(key=lambda p: p[1])
    z0, z1 = math.ceil(pts[0][1] / 100) * 100, math.floor(pts[-1][1] / 100) * 100
    xs = []
    for z in range(z0, z1 + 1, 100):
        k = max(i for i in range(len(pts) - 1) if pts[i][1] <= z)
        a, b = pts[k], pts[min(k + 1, len(pts) - 1)]
        t = 0 if b[1] == a[1] else (z - a[1]) / (b[1] - a[1])
        xs.append(round(a[0] + (b[0] - a[0]) * t))
    print('// Wadi al-Aqiq: (c) OpenStreetMap contributors, ODbL (ways 960090164, 1235902746); x of the course every 100 m of z')
    print(f"const AQIQ = {{ z0: {z0}, n: {len(xs)}, x: [{', '.join(map(str, xs))}] }};")
